-- MathSpark diagnostic history migration.
-- Safe additive migration: does not drop, truncate, or rewrite existing exam/attempt rows.
-- Run once in Supabase Dashboard > SQL Editor.

create table if not exists public.mathspark_diagnostic_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  exam_attempt_id bigint references public.exam_attempts(id) on delete set null,
  exam_id bigint references public.learning_exams(id) on delete set null,
  question_id text not null,
  parallel_key text,
  skill_code text check (skill_code is null or skill_code in ('KT01','KT02','KT03','KT04','KT05','KT06','KT07')),
  error_code text check (error_code is null or error_code in ('L01','L02','L03','L04','L05','L06','L07','L08','L09')),
  evidence text,
  is_correct boolean not null,
  is_repeat_attempt boolean not null default false,
  selected_options text[] not null default '{}',
  omitted_correct_options text[] not null default '{}',
  diagnosis_status text not null default 'FIRST_ATTEMPT'
    check (diagnosis_status in ('FIRST_ATTEMPT','SLIP_RESOLVED','PERSISTENT_GAP','STABLE')),
  created_at timestamptz not null default now()
);

-- Additive guards also repair an earlier partial creation without deleting data.
alter table public.mathspark_diagnostic_events add column if not exists evidence text;
alter table public.mathspark_diagnostic_events add column if not exists is_repeat_attempt boolean not null default false;
alter table public.mathspark_diagnostic_events alter column parallel_key drop not null;

create index if not exists mathspark_diag_user_parallel_created_idx
  on public.mathspark_diagnostic_events(user_id, parallel_key, created_at desc);
create index if not exists mathspark_diag_attempt_idx
  on public.mathspark_diagnostic_events(exam_attempt_id);

alter table public.mathspark_diagnostic_events enable row level security;
revoke all on table public.mathspark_diagnostic_events from anon, authenticated;
grant all on table public.mathspark_diagnostic_events to service_role;
grant usage, select on sequence public.mathspark_diagnostic_events_id_seq to service_role;
