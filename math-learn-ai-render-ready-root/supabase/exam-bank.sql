-- MathSpark Exam Bank migration
-- Run once in Supabase Dashboard > SQL Editor > New query.
-- The server uses SUPABASE_SERVICE_ROLE_KEY for all exam management and scoring.

create table if not exists public.learning_exams (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null default '',
  duration_minutes integer not null default 120 check (duration_minutes between 10 and 360),
  status text not null default 'draft' check (status in ('draft','published')),
  source_file_name text not null default '',
  source_file_path text,
  questions jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.exam_attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  exam_id bigint references public.learning_exams(id) on delete set null,
  exam_title text not null,
  score numeric not null default 0,
  max_score numeric not null default 0,
  result_json jsonb not null default '{}'::jsonb,
  submitted_at timestamptz not null default now()
);

create index if not exists learning_exams_status_created_idx on public.learning_exams(status, created_at desc);
create index if not exists exam_attempts_user_submitted_idx on public.exam_attempts(user_id, submitted_at desc);

alter table public.learning_exams enable row level security;
alter table public.exam_attempts enable row level security;
revoke all on table public.learning_exams from anon, authenticated;
grant all on table public.learning_exams to service_role;
revoke all on table public.exam_attempts from anon, authenticated;
grant select on table public.exam_attempts to authenticated;
grant all on table public.exam_attempts to service_role;
grant usage, select on sequence public.learning_exams_id_seq to service_role;
grant usage, select on sequence public.exam_attempts_id_seq to service_role;

drop policy if exists "Students read own exam attempts" on public.exam_attempts;
create policy "Students read own exam attempts" on public.exam_attempts
  for select to authenticated using ((select auth.uid()) = user_id);

