-- MathSpark Supabase setup
-- Run this entire script once in Supabase Dashboard > SQL Editor > New query.
-- Educational documents in the storage bucket are public-read, because all students are intended to read them.
-- Upload/update/delete operations are performed only by the server using a secret key, never by the browser.

create table if not exists public.student_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.student_learning_state (
  user_id uuid primary key references auth.users(id) on delete cascade,
  payload jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.learning_documents (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null default '',
  category text not null default 'chuyen-de' check (category in ('chuyen-de','de-vao-10','de-giua-ky','de-cuoi-ky')),
  tags text not null default '',
  author text not null default 'Ban quản trị',
  file_name text not null default '',
  file_path text,
  file_type text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.student_profiles enable row level security;
alter table public.student_learning_state enable row level security;
alter table public.learning_documents enable row level security;

revoke all on table public.student_profiles from anon, authenticated;
grant select, update on table public.student_profiles to authenticated;
revoke all on table public.student_learning_state from anon, authenticated;
grant select, insert, update, delete on table public.student_learning_state to authenticated;
revoke all on table public.learning_documents from anon, authenticated;
grant all on table public.learning_documents to service_role;
grant usage, select on sequence public.learning_documents_id_seq to service_role;

drop policy if exists "Students read own profile" on public.student_profiles;
create policy "Students read own profile" on public.student_profiles
  for select to authenticated using ((select auth.uid()) = id);
drop policy if exists "Students update own profile" on public.student_profiles;
create policy "Students update own profile" on public.student_profiles
  for update to authenticated using ((select auth.uid()) = id) with check ((select auth.uid()) = id);

drop policy if exists "Students read own learning state" on public.student_learning_state;
create policy "Students read own learning state" on public.student_learning_state
  for select to authenticated using ((select auth.uid()) = user_id);
drop policy if exists "Students insert own learning state" on public.student_learning_state;
create policy "Students insert own learning state" on public.student_learning_state
  for insert to authenticated with check ((select auth.uid()) = user_id);
drop policy if exists "Students update own learning state" on public.student_learning_state;
create policy "Students update own learning state" on public.student_learning_state
  for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
drop policy if exists "Students delete own learning state" on public.student_learning_state;
create policy "Students delete own learning state" on public.student_learning_state
  for delete to authenticated using ((select auth.uid()) = user_id);

create or replace function public.mathspark_handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.student_profiles (id, display_name)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'display_name', ''))
  on conflict (id) do update set display_name = excluded.display_name, updated_at = now();
  insert into public.student_learning_state (user_id, payload)
  values (new.id, '{}'::jsonb)
  on conflict (user_id) do nothing;
  return new;
end;
$$;

drop trigger if exists mathspark_on_auth_user_created on auth.users;
create trigger mathspark_on_auth_user_created
after insert on auth.users
for each row execute procedure public.mathspark_handle_new_user();

